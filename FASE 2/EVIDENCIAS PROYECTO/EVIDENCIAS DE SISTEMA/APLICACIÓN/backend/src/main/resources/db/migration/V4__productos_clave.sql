-- V4 · Productos clave: lista personal de productos que cada usuario quiere seguir de cerca en el panel de analítica.
--
-- Es una preferencia, no un registro contable: sin Envers, sin triggers y con borrado en cascada (si se borra el
-- usuario o el producto, desaparece la fila). Un producto aparece una sola vez por usuario.

CREATE TABLE productos_clave (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   timestamp(6) NOT NULL DEFAULT now(),
    updated_at   timestamp(6) NOT NULL DEFAULT now(),
    usuario_id   bigint       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    producto_id  bigint       NOT NULL REFERENCES productos (id) ON DELETE CASCADE,
    CONSTRAINT uq_productos_clave_usuario_producto UNIQUE (usuario_id, producto_id)
);

CREATE INDEX ix_productos_clave_usuario ON productos_clave (usuario_id);
