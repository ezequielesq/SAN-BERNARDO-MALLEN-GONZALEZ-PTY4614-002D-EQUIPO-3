-- V3 · Agenda compartida de eventos del calendario de los bodegueros.
--
-- Es una agenda, no un registro histórico: sin Envers y sin triggers. Cualquier bodeguero ve, crea,
-- edita y borra cualquier evento (el acceso se restringe por rol en la API, no por fila).
-- creado_por solo identifica a quien lo agendó; hora nula = evento de todo el día.

CREATE TABLE eventos (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    updated_at  timestamp(6) NOT NULL DEFAULT now(),
    titulo      varchar(120) NOT NULL,
    fecha       date         NOT NULL,
    hora        time         NULL,
    descripcion varchar(500) NULL,
    creado_por  bigint       NOT NULL REFERENCES usuarios (id),
    CONSTRAINT ck_eventos_titulo CHECK (length(btrim(titulo)) > 0)
);

CREATE INDEX ix_eventos_fecha ON eventos (fecha);
