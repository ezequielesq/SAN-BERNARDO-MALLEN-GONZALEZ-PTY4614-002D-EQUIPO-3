-- V5 · Proveedores. Cada lote nace con el proveedor de su compra (nulo en inventario inicial y ajustes).
-- Es DDL: el trigger de inmutabilidad de lotes (UPDATE/DELETE) no interviene. Los lotes anteriores quedan sin proveedor.

CREATE TABLE proveedores (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    updated_at  timestamp(6) NOT NULL DEFAULT now(),
    rut         varchar(12)  NOT NULL,
    nombre      varchar(100) NOT NULL,
    activo      boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_proveedores_rut UNIQUE (rut)
);
CREATE UNIQUE INDEX uq_proveedores_nombre ON proveedores (lower(nombre));

ALTER TABLE lotes ADD COLUMN proveedor_id bigint REFERENCES proveedores (id);
CREATE INDEX ix_lotes_proveedor ON lotes (proveedor_id);
