    nombre        varchar(50)  NOT NULL,
    activo        boolean      NOT NULL DEFAULT true,
    requiere_ptv  boolean      NOT NULL DEFAULT false,
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre)
);

CREATE TABLE unidades_medida (
