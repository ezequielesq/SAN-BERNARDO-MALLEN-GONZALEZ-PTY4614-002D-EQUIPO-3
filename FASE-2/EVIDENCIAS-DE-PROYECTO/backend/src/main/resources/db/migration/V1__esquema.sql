-- 6. Triggers
-- Los mensajes de RAISE EXCEPTION son legibles: el backend los muestra al usuario.
-- ---------------------------------------------------------------------

-- INM · el libro es su propia auditoría: operaciones, movimientos y lotes no se tocan.
CREATE FUNCTION fn_tabla_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'El registro de % es histórico: no admite % (se corrige con una operación contraria).',
        TG_TABLE_NAME, TG_OP;
END $$;

CREATE TRIGGER trg_operaciones_inmutable BEFORE UPDATE OR DELETE ON operaciones
    FOR EACH ROW EXECUTE FUNCTION fn_tabla_inmutable();
CREATE TRIGGER trg_movimientos_inmutable BEFORE UPDATE OR DELETE ON movimientos
    FOR EACH ROW EXECUTE FUNCTION fn_tabla_inmutable();
CREATE TRIGGER trg_lotes_inmutable BEFORE UPDATE OR DELETE ON lotes
    FOR EACH ROW EXECUTE FUNCTION fn_tabla_inmutable();

-- INM · una solicitud resuelta (y sus líneas) no se modifica. Al resolver se exige el bodeguero.
CREATE FUNCTION fn_solicitudes_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_pendiente bigint;
BEGIN
    SELECT id INTO v_pendiente FROM estados_solicitud WHERE codigo = 'PENDIENTE';
    IF OLD.estado_id <> v_pendiente THEN
        RAISE EXCEPTION 'La solicitud % ya fue resuelta y no admite cambios.', OLD.id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    IF NEW.estado_id <> v_pendiente AND NEW.bodeguero_id IS NULL THEN
        RAISE EXCEPTION 'Al resolver la solicitud % debe indicarse el bodeguero.', OLD.id;
    END IF;
    IF NEW.estado_id = v_pendiente AND NEW.bodeguero_id IS NOT NULL THEN
        RAISE EXCEPTION 'Una solicitud pendiente no puede tener bodeguero.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_solicitudes_inmutable BEFORE UPDATE OR DELETE ON solicitudes
    FOR EACH ROW EXECUTE FUNCTION fn_solicitudes_inmutable();

CREATE FUNCTION fn_detalle_solicitudes_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_estado text;
BEGIN
    SELECT e.codigo INTO v_estado
      FROM solicitudes s JOIN estados_solicitud e ON e.id = s.estado_id
     WHERE s.id = OLD.solicitud_id;
    IF v_estado IS DISTINCT FROM 'PENDIENTE' THEN
        RAISE EXCEPTION 'Las líneas de la solicitud % no se modifican: ya fue resuelta.', OLD.solicitud_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_detalle_solicitudes_inmutable BEFORE UPDATE OR DELETE ON detalle_solicitudes
    FOR EACH ROW EXECUTE FUNCTION fn_detalle_solicitudes_inmutable();

-- INM · tampoco se agregan líneas a una solicitud que ya fue resuelta.
CREATE FUNCTION fn_detalle_solicitudes_solo_pendiente() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_estado text;
BEGIN
    SELECT e.codigo INTO v_estado
      FROM solicitudes s JOIN estados_solicitud e ON e.id = s.estado_id
     WHERE s.id = NEW.solicitud_id;
    IF v_estado IS DISTINCT FROM 'PENDIENTE' THEN
        RAISE EXCEPTION 'No se pueden agregar líneas a la solicitud %: ya fue resuelta.', NEW.solicitud_id;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_detalle_solicitudes_insert_pendiente BEFORE INSERT ON detalle_solicitudes
    FOR EACH ROW EXECUTE FUNCTION fn_detalle_solicitudes_solo_pendiente();

-- T1 · el saldo de un lote nunca queda negativo (restricción diferida: se evalúa al confirmar).
--      Se toma antes un bloqueo de fila sobre el lote (FOR NO KEY UPDATE: no choca con las FK ni
--      dispara INM) para que dos transacciones concurrentes no validen contra el mismo saldo.
CREATE FUNCTION fn_t1_saldo_lote_no_negativo() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_saldo bigint;
BEGIN
    PERFORM 1 FROM lotes WHERE id = NEW.lote_id FOR NO KEY UPDATE;
    SELECT COALESCE(SUM(m.cantidad * t.sentido), 0) INTO v_saldo
      FROM movimientos m
      JOIN operaciones o ON o.id = m.operacion_id
      JOIN tipos_operacion t ON t.id = o.tipo_id
     WHERE m.lote_id = NEW.lote_id;
    IF v_saldo < 0 THEN
        RAISE EXCEPTION 'El lote % quedaría con saldo negativo (%): no hay stock suficiente.', NEW.lote_id, v_saldo;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t1_saldo_lote AFTER INSERT ON movimientos
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_t1_saldo_lote_no_negativo();

-- T2 · lo devuelto por lote no supera lo entregado en el pedido de origen.
CREATE FUNCTION fn_t2_devuelto_no_supera_entregado() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_pedido     bigint;
    v_devolvible integer;
BEGIN
    SELECT s.solicitud_origen_id INTO v_pedido
      FROM operaciones o
      JOIN tipos_operacion t ON t.id = o.tipo_id AND t.solicitud_requerida = 'DEVOLUCION'
      JOIN solicitudes s ON s.id = o.solicitud_id
     WHERE o.id = NEW.operacion_id;
    IF v_pedido IS NULL THEN
        RETURN NULL;
    END IF;
    -- Bloqueo de fila del pedido de origen: serializa devoluciones concurrentes del mismo pedido.
    PERFORM 1 FROM solicitudes WHERE id = v_pedido FOR NO KEY UPDATE;
    SELECT devolvible INTO v_devolvible
      FROM devolvible_lote
     WHERE pedido_id = v_pedido AND lote_id = NEW.lote_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El lote % no formó parte del pedido %: no se puede devolver.', NEW.lote_id, v_pedido;
    END IF;
    IF v_devolvible < 0 THEN
        RAISE EXCEPTION 'Se devolvería más de lo entregado del lote % en el pedido %.', NEW.lote_id, v_pedido;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t2_devuelto AFTER INSERT ON movimientos
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_t2_devuelto_no_supera_entregado();

-- T3 · la operación es coherente con su tipo (antes de insertar).
--      Sin solicitud_requerida no lleva solicitud; con ella lleva una solicitud PENDIENTE de esa clase.
--      Una corrección solo aplica a una operación manual (tipo seleccionable) de sentido contrario.
CREATE FUNCTION fn_t3_operacion_coherente() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_tipo          tipos_operacion%ROWTYPE;
    v_tipo_orig     tipos_operacion%ROWTYPE;
    v_estado        text;
    v_origen        bigint;
    v_es_correccion boolean;
BEGIN
    SELECT * INTO v_tipo FROM tipos_operacion WHERE id = NEW.tipo_id;
    v_es_correccion := v_tipo.codigo IN ('CORRECCION_AUMENTA', 'CORRECCION_DISMINUYE');

    IF v_tipo.solicitud_requerida IS NULL THEN
        IF NEW.solicitud_id IS NOT NULL THEN
            RAISE EXCEPTION 'La operación "%" no nace de una solicitud.', v_tipo.nombre;
        END IF;
    ELSE
        IF NEW.solicitud_id IS NULL THEN
            RAISE EXCEPTION 'La operación "%" exige una solicitud.', v_tipo.nombre;
        END IF;
        SELECT e.codigo, s.solicitud_origen_id INTO v_estado, v_origen
          FROM solicitudes s JOIN estados_solicitud e ON e.id = s.estado_id
         WHERE s.id = NEW.solicitud_id;
        IF v_estado IS DISTINCT FROM 'PENDIENTE' THEN
            RAISE EXCEPTION 'La solicitud % ya fue procesada.', NEW.solicitud_id;
        END IF;
        IF (v_tipo.solicitud_requerida = 'PEDIDO') <> (v_origen IS NULL) THEN
            RAISE EXCEPTION 'La operación "%" no corresponde a la clase de la solicitud %.', v_tipo.nombre, NEW.solicitud_id;
        END IF;
    END IF;

    IF v_es_correccion THEN
        IF NEW.operacion_corregida_id IS NULL THEN
            RAISE EXCEPTION 'Una corrección debe indicar la operación que corrige.';
        END IF;
        SELECT t.* INTO v_tipo_orig
          FROM operaciones o JOIN tipos_operacion t ON t.id = o.tipo_id
         WHERE o.id = NEW.operacion_corregida_id;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'La operación a corregir no existe.';
        END IF;
        IF NOT v_tipo_orig.seleccionable THEN
            RAISE EXCEPTION 'Solo se corrigen operaciones registradas a mano; las de solicitudes se deshacen con una devolución.';
        END IF;
        IF v_tipo_orig.sentido = v_tipo.sentido THEN
            RAISE EXCEPTION 'La corrección debe tener sentido contrario al de la operación corregida.';
        END IF;
    ELSIF NEW.operacion_corregida_id IS NOT NULL THEN
        RAISE EXCEPTION 'Solo las correcciones indican una operación corregida.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_t3_operacion BEFORE INSERT ON operaciones
    FOR EACH ROW EXECUTE FUNCTION fn_t3_operacion_coherente();

-- T4 · la solicitud de origen de una devolución es un pedido APROBADO.
CREATE FUNCTION fn_t4_origen_es_pedido_aprobado() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_estado        text;
    v_origen_origen bigint;
BEGIN
    IF NEW.solicitud_origen_id IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT e.codigo, s.solicitud_origen_id INTO v_estado, v_origen_origen
      FROM solicitudes s JOIN estados_solicitud e ON e.id = s.estado_id
     WHERE s.id = NEW.solicitud_origen_id;
    IF v_estado IS DISTINCT FROM 'APROBADA' OR v_origen_origen IS NOT NULL THEN
        RAISE EXCEPTION 'Solo se pueden devolver productos de pedidos aprobados.';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_t4_origen BEFORE INSERT OR UPDATE ON solicitudes
    FOR EACH ROW EXECUTE FUNCTION fn_t4_origen_es_pedido_aprobado();

-- T5 · una solicitud está APROBADA si y solo si existe su operación (restricciones diferidas).
CREATE FUNCTION fn_t5a_aprobada_tiene_operacion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_estado text;
BEGIN
    SELECT codigo INTO v_estado FROM estados_solicitud WHERE id = NEW.estado_id;
    IF v_estado = 'APROBADA' AND NOT EXISTS (SELECT 1 FROM operaciones WHERE solicitud_id = NEW.id) THEN
        RAISE EXCEPTION 'La solicitud % no puede quedar aprobada sin su operación de stock.', NEW.id;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t5a_aprobada AFTER INSERT OR UPDATE ON solicitudes
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_t5a_aprobada_tiene_operacion();

CREATE FUNCTION fn_t5b_operacion_de_solicitud_aprobada() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_estado text;
BEGIN
    SELECT e.codigo INTO v_estado
      FROM solicitudes s JOIN estados_solicitud e ON e.id = s.estado_id
     WHERE s.id = NEW.solicitud_id;
    IF v_estado IS DISTINCT FROM 'APROBADA' THEN
        RAISE EXCEPTION 'La solicitud % tiene operación de stock pero no quedó aprobada.', NEW.solicitud_id;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t5b_operacion AFTER INSERT ON operaciones
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW WHEN (NEW.solicitud_id IS NOT NULL)
    EXECUTE FUNCTION fn_t5b_operacion_de_solicitud_aprobada();

-- T6 · toda operación tiene al menos un movimiento.
CREATE FUNCTION fn_t6_operacion_con_movimientos() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM movimientos WHERE operacion_id = NEW.id) THEN
        RAISE EXCEPTION 'La operación % no tiene movimientos.', NEW.id;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t6_operacion AFTER INSERT ON operaciones
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_t6_operacion_con_movimientos();

-- T7 (R1) · todo lote nace con al menos un movimiento de entrada: el saldo derivado depende de él.
CREATE FUNCTION fn_t7_lote_con_entrada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM movimientos m
          JOIN operaciones o ON o.id = m.operacion_id
          JOIN tipos_operacion t ON t.id = o.tipo_id
         WHERE m.lote_id = NEW.id AND t.sentido = 1
    ) THEN
        RAISE EXCEPTION 'El lote % no tiene un movimiento de entrada.', NEW.id;
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER trg_t7_lote AFTER INSERT ON lotes
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_t7_lote_con_entrada();

