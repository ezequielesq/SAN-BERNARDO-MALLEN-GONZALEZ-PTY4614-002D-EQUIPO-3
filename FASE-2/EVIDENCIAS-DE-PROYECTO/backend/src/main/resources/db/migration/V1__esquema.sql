CREATE TABLE usuarios (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    updated_at  timestamp(6) NOT NULL DEFAULT now(),
    rol_id      bigint       NOT NULL REFERENCES roles (id),
    nombre      varchar(100) NOT NULL,
    email       varchar(150) NOT NULL,
    password    varchar(255) NOT NULL,
    activo      boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE TABLE productos (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        timestamp(6) NOT NULL DEFAULT now(),
    updated_at        timestamp(6) NOT NULL DEFAULT now(),
    categoria_id      bigint       NOT NULL REFERENCES categorias (id),
    unidad_medida_id  bigint       NOT NULL REFERENCES unidades_medida (id),
    nombre            varchar(150) NOT NULL,
    codigo_ptv        varchar(20),
    codigo            varchar(20),
    es_perecible      boolean      NOT NULL,
    stock_minimo      integer      NOT NULL DEFAULT 0,
    stock_critico     integer      NOT NULL DEFAULT 0,
    -- Costo de referencia: se sugiere al ingresar un lote; la valorización usa el costo del lote.
    costo_unitario    integer,
    activo            boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_productos_codigo_ptv UNIQUE (codigo_ptv),
    CONSTRAINT uq_productos_codigo UNIQUE (codigo),
    CONSTRAINT ck_productos_umbrales CHECK (stock_critico >= 0 AND stock_critico <= stock_minimo),
    CONSTRAINT ck_productos_costo CHECK (costo_unitario IS NULL OR costo_unitario >= 0)
);

-- Un lote es la representación física de una tanda de un producto. Inmutable (trigger INM).
CREATE TABLE lotes (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         timestamp(6) NOT NULL DEFAULT now(),
    updated_at         timestamp(6) NOT NULL DEFAULT now(),
    producto_id        bigint       NOT NULL REFERENCES productos (id),
    numero_lote        varchar(50),
    fecha_vencimiento  date,
    costo_unitario     integer,
    CONSTRAINT ck_lotes_costo CHECK (costo_unitario IS NULL OR costo_unitario >= 0)
);

CREATE TABLE solicitudes (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamp(6) NOT NULL DEFAULT now(),
    updated_at           timestamp(6) NOT NULL DEFAULT now(),
    estado_id            bigint       NOT NULL REFERENCES estados_solicitud (id),
    solicitante_id       bigint       NOT NULL REFERENCES usuarios (id),
    -- Quien resuelve (aprueba o rechaza). Nulo mientras está pendiente.
    bodeguero_id         bigint       REFERENCES usuarios (id),
    -- Nulo = pedido; con valor = devolución de ese pedido.
    solicitud_origen_id  bigint       REFERENCES solicitudes (id),
    observacion          varchar(300),
    CONSTRAINT ck_solicitudes_sin_autorreferencia CHECK (solicitud_origen_id IS NULL OR solicitud_origen_id <> id)
);

CREATE TABLE detalle_solicitudes (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamp(6) NOT NULL DEFAULT now(),
    updated_at           timestamp(6) NOT NULL DEFAULT now(),
    solicitud_id         bigint  NOT NULL REFERENCES solicitudes (id),
    producto_id          bigint  NOT NULL REFERENCES productos (id),
    cantidad_solicitada  integer NOT NULL,
    CONSTRAINT ck_detalle_solicitudes_cantidad CHECK (cantidad_solicitada > 0),
    CONSTRAINT uq_detalle_solicitudes_solicitud_producto UNIQUE (solicitud_id, producto_id)
);

-- Cabecera del libro. La fecha de la operación es created_at. Inmutable (trigger INM).
CREATE TABLE operaciones (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at              timestamp(6) NOT NULL DEFAULT now(),
    updated_at              timestamp(6) NOT NULL DEFAULT now(),
    tipo_id                 bigint NOT NULL REFERENCES tipos_operacion (id),
    -- Quien movió el stock (en las solicitudes aprobadas coincide con solicitudes.bodeguero_id).
    usuario_id              bigint NOT NULL REFERENCES usuarios (id),
    -- Una solicitud tiene a lo más una operación: impide aprobarla dos veces.
    solicitud_id            bigint REFERENCES solicitudes (id),
    -- Una operación se corrige a lo más una vez.
    operacion_corregida_id  bigint REFERENCES operaciones (id),
    nota                    varchar(300),
    CONSTRAINT uq_operaciones_solicitud UNIQUE (solicitud_id),
    CONSTRAINT uq_operaciones_corregida UNIQUE (operacion_corregida_id),
    CONSTRAINT ck_operaciones_sin_autorreferencia CHECK (operacion_corregida_id IS NULL OR operacion_corregida_id <> id)
);

-- Línea del libro: cuánto de qué lote. La cantidad es siempre positiva; el signo sale de
-- tipos_operacion.sentido. Inmutable (trigger INM).
CREATE TABLE movimientos (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamp(6) NOT NULL DEFAULT now(),
    updated_at    timestamp(6) NOT NULL DEFAULT now(),
    operacion_id  bigint  NOT NULL REFERENCES operaciones (id),
    lote_id       bigint  NOT NULL REFERENCES lotes (id),
    cantidad      integer NOT NULL,
    CONSTRAINT ck_movimientos_cantidad CHECK (cantidad > 0),
    CONSTRAINT uq_movimientos_operacion_lote UNIQUE (operacion_id, lote_id)
);

