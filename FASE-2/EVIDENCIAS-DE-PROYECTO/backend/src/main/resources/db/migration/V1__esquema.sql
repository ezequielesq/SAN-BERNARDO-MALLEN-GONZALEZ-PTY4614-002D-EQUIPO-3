    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    updated_at  timestamp(6) NOT NULL DEFAULT now(),
    codigo      varchar(20)  NOT NULL,
    nombre      varchar(50)  NOT NULL,
    activo      boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_roles_codigo UNIQUE (codigo)
);

CREATE TABLE estados_solicitud (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    updated_at  timestamp(6) NOT NULL DEFAULT now(),
    codigo      varchar(20)  NOT NULL,
    nombre      varchar(50)  NOT NULL,
    CONSTRAINT uq_estados_solicitud_codigo UNIQUE (codigo)
);

CREATE TABLE tipos_operacion (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamp(6) NOT NULL DEFAULT now(),
    updated_at           timestamp(6) NOT NULL DEFAULT now(),
    codigo               varchar(30)  NOT NULL,
    nombre               varchar(60)  NOT NULL,
    sentido              smallint     NOT NULL,
    solicitud_requerida  varchar(10),
    seleccionable        boolean      NOT NULL,
    CONSTRAINT uq_tipos_operacion_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipos_operacion_sentido CHECK (sentido IN (1, -1)),
    CONSTRAINT ck_tipos_operacion_solicitud CHECK (solicitud_requerida IN ('PEDIDO', 'DEVOLUCION')),
    -- Lo que nace de una solicitud lo genera el sistema: no se elige a mano.
    CONSTRAINT ck_tipos_operacion_sistema CHECK (solicitud_requerida IS NULL OR NOT seleccionable)
);

CREATE TABLE categorias (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
