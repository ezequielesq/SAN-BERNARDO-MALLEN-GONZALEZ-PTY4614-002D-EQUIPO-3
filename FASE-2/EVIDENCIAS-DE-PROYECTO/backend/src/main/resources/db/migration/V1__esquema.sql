-- 5. Vistas (comunes, no materializadas)
-- ---------------------------------------------------------------------

-- Saldo por lote: suma de movimientos con el signo del tipo de operación.
CREATE VIEW saldo_lote AS
SELECT l.id AS lote_id,
       l.producto_id,
       l.fecha_vencimiento,
       l.costo_unitario,
       COALESCE(SUM(m.cantidad * t.sentido), 0)::integer AS saldo
  FROM lotes l
  LEFT JOIN movimientos m ON m.lote_id = l.id
  LEFT JOIN operaciones o ON o.id = m.operacion_id
  LEFT JOIN tipos_operacion t ON t.id = o.tipo_id
 GROUP BY l.id;

-- Stock por producto (una fila por producto, también los que no tienen lotes) y su estado.
-- valor = suma de saldo × costo del lote, solo de los lotes con costo; nulo si ninguno lo tiene.
CREATE VIEW stock_producto AS
SELECT p.id AS producto_id,
       COALESCE(SUM(s.saldo), 0)::integer AS stock,
       SUM(s.saldo::bigint * s.costo_unitario) AS valor,
       CASE
           WHEN COALESCE(SUM(s.saldo), 0) <= 0              THEN 'AGOTADO'
           WHEN SUM(s.saldo) <= p.stock_critico             THEN 'CRITICO'
           WHEN SUM(s.saldo) <= p.stock_minimo              THEN 'BAJO'
           ELSE 'NORMAL'
       END AS estado
  FROM productos p
  LEFT JOIN saldo_lote s ON s.producto_id = p.id
 GROUP BY p.id;

-- Lo pedido contra lo entregado (o aceptado, en una devolución), por solicitud y producto.
-- Un producto con entregado y sin línea pedida es un "agregado".
CREATE VIEW solicitado_vs_entregado AS
WITH operado AS (
    SELECT o.solicitud_id, l.producto_id, SUM(m.cantidad)::integer AS cantidad
      FROM operaciones o
      JOIN movimientos m ON m.operacion_id = o.id
      JOIN lotes l ON l.id = m.lote_id
     WHERE o.solicitud_id IS NOT NULL
     GROUP BY o.solicitud_id, l.producto_id
), cruce AS (
    SELECT COALESCE(d.solicitud_id, e.solicitud_id) AS solicitud_id,
           COALESCE(d.producto_id, e.producto_id)   AS producto_id,
           d.cantidad_solicitada,
           e.cantidad                               AS cantidad_operada,
           (d.id IS NULL)                           AS agregado
      FROM detalle_solicitudes d
      FULL OUTER JOIN operado e
        ON e.solicitud_id = d.solicitud_id AND e.producto_id = d.producto_id
)
SELECT c.solicitud_id,
       c.producto_id,
       c.cantidad_solicitada,
       CASE WHEN es.codigo = 'APROBADA' THEN COALESCE(c.cantidad_operada, 0) END AS cantidad_entregada,
       c.agregado
  FROM cruce c
  JOIN solicitudes s ON s.id = c.solicitud_id
  JOIN estados_solicitud es ON es.id = s.estado_id;

-- Por pedido y lote: lo entregado menos lo ya devuelto por las devoluciones aprobadas.
-- movimiento_id permite devolver "empezando por el último lote consumido".
CREATE VIEW devolvible_lote AS
SELECT o.solicitud_id AS pedido_id,
       m.lote_id,
       l.producto_id,
       m.id AS movimiento_id,
       m.cantidad AS entregado,
       COALESCE(d.cantidad, 0)::integer AS devuelto,
       (m.cantidad - COALESCE(d.cantidad, 0))::integer AS devolvible
  FROM operaciones o
  JOIN tipos_operacion t ON t.id = o.tipo_id AND t.solicitud_requerida = 'PEDIDO'
  JOIN movimientos m ON m.operacion_id = o.id
  JOIN lotes l ON l.id = m.lote_id
  LEFT JOIN (
        SELECT s.solicitud_origen_id AS pedido_id, md.lote_id, SUM(md.cantidad) AS cantidad
          FROM solicitudes s
          JOIN operaciones od ON od.solicitud_id = s.id
          JOIN movimientos md ON md.operacion_id = od.id
         WHERE s.solicitud_origen_id IS NOT NULL
         GROUP BY s.solicitud_origen_id, md.lote_id
  ) d ON d.pedido_id = o.solicitud_id AND d.lote_id = m.lote_id;

